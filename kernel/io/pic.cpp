#include "io.h"

void pic_init() {
    // ICW1 - Init
    outb(0x20, 0x11);
    outb(0xA0, 0x11);

    // ICW2 - Remap: Master at 0x20 (32), Slave at 0x28 (40)
    outb(0x21, 0x20);
    outb(0xA1, 0x28);

    // ICW3 - Cascading
    outb(0x21, 0x04);
    outb(0xA1, 0x02);

    // ICW4
    outb(0x21, 0x01);
    outb(0xA1, 0x01);

    // All IRQs except Keyboard
    outb(0x21, 0xFD);
    outb(0xA1, 0xFF);
}
